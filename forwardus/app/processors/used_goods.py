# 예전 형식(문구만 모은 목록) — 다른 곳이 쓰던 이름. 품목을 가리지 않고 모두 돌려줍니다.
NOTES: dict[str, list[str]] = {code: [text for text, _ in rows] for code, rows in NOTE_ROWS.items()}


def _fits(chapters: set[str] | None, wanted: set[str] | None) -> bool:
    return not chapters or wanted is None or bool(chapters & wanted)


def notes_for(country_code: str, chapters: set[str] | None = None) -> list[str]:
    """그 나라의 중고 규제 안내. chapters(이 건의 HS 앞 두 자리)가 있으면 그 품목에 걸리는 문구만."""

    code = (country_code or "").strip().upper()
    rows = NOTE_ROWS.get(code)
    if rows is None:
        try:
            from app.processors import country_export_guide
            if code in country_export_guide._eu_members():           # EU 는 같은 규정 — 독일 줄을 씁니다
                rows = NOTE_ROWS["DE"]
        except Exception:                                              # noqa: BLE001
            rows = None
    return [text for text, wanted in (rows or []) if _fits(chapters, wanted)]
